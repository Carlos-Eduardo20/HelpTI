-- HelpTI Oracle schema
-- Standalone reference schema. This script is not used by the Flask application.
-- Run once while connected to the Oracle schema/user dedicated to HelpTI.

CREATE TABLE usuario (
    id_usuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome VARCHAR2(255),
    contato VARCHAR2(255),
    email VARCHAR2(320),
    telefone VARCHAR2(30),
    telefone_empresa VARCHAR2(30),
    endereco VARCHAR2(1000),
    status VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    tipo_usuario VARCHAR2(30) DEFAULT 'CLIENTE' NOT NULL,
    cnpj VARCHAR2(18),
    plano VARCHAR2(255),
    acoes CLOB,
    senha_hash VARCHAR2(255),
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario)
);

CREATE TABLE cliente (
    id_cliente NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    nome VARCHAR2(255) NOT NULL,
    contato VARCHAR2(255),
    email VARCHAR2(320) NOT NULL,
    telefone VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE tipo_chamado (
    id_tipo_chamado NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome VARCHAR2(255) NOT NULL,
    classificacao VARCHAR2(255),
    descricao VARCHAR2(2000),
    CONSTRAINT pk_tipo_chamado PRIMARY KEY (id_tipo_chamado)
);

CREATE TABLE setor (
    id_setor NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome VARCHAR2(255) NOT NULL,
    descricao VARCHAR2(2000),
    niveis CLOB,
    CONSTRAINT pk_setor PRIMARY KEY (id_setor),
    CONSTRAINT uq_setor_nome UNIQUE (nome)
);

CREATE TABLE grupo_solucionadores (
    id_grupo_solucionadores NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    descricao VARCHAR2(1000),
    nivel NUMBER(10),
    data_inicio DATE,
    data_fim DATE,
    nome VARCHAR2(255),
    email VARCHAR2(320),
    cargo VARCHAR2(255),
    setor VARCHAR2(255),
    valor_hora NUMBER(12, 2),
    telefone VARCHAR2(30),
    status VARCHAR2(30) DEFAULT 'ATIVO' NOT NULL,
    senha VARCHAR2(255) DEFAULT '' NOT NULL,
    permissoes CLOB DEFAULT '[]' NOT NULL,
    id_usuario NUMBER NOT NULL,
    id_setor NUMBER,
    CONSTRAINT pk_grupo_solucionadores PRIMARY KEY (id_grupo_solucionadores),
    CONSTRAINT fk_grupo_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_grupo_setor FOREIGN KEY (id_setor)
        REFERENCES setor (id_setor) ON DELETE SET NULL
);

CREATE TABLE chamado (
    id_chamado NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_tipo_chamado NUMBER DEFAULT 1 NOT NULL,
    id_setor NUMBER,
    setor VARCHAR2(255),
    id_grupo_solucionadores NUMBER,
    status VARCHAR2(30) DEFAULT 'ABERTO' NOT NULL,
    cliente VARCHAR2(255) NOT NULL,
    assunto VARCHAR2(1000),
    descricao CLOB,
    email_cliente VARCHAR2(320),
    telefone_cliente VARCHAR2(30),
    contato_cliente VARCHAR2(255),
    telefone_contato VARCHAR2(30),
    descricao_final CLOB,
    documentacao CLOB,
    tempo_decorrido_segundos NUMBER(12) DEFAULT 0 NOT NULL,
    tempo_inicio TIMESTAMP,
    data_abertura TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    data_fechamento TIMESTAMP,
    data_agendada DATE,
    hora_agendada VARCHAR2(8),
    classificacao VARCHAR2(255),
    id_usuario NUMBER,
    CONSTRAINT pk_chamado PRIMARY KEY (id_chamado),
    CONSTRAINT fk_chamado_tipo FOREIGN KEY (id_tipo_chamado)
        REFERENCES tipo_chamado (id_tipo_chamado),
    CONSTRAINT fk_chamado_setor FOREIGN KEY (id_setor)
        REFERENCES setor (id_setor) ON DELETE SET NULL,
    CONSTRAINT fk_chamado_responsavel FOREIGN KEY (id_grupo_solucionadores)
        REFERENCES grupo_solucionadores (id_grupo_solucionadores) ON DELETE SET NULL,
    CONSTRAINT fk_chamado_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE historico_chamado (
    id_historico NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_chamado NUMBER NOT NULL,
    evento VARCHAR2(100) NOT NULL,
    descricao CLOB NOT NULL,
    autor VARCHAR2(255) DEFAULT 'Sistema' NOT NULL,
    data_evento TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_historico_chamado PRIMARY KEY (id_historico),
    CONSTRAINT fk_historico_chamado FOREIGN KEY (id_chamado)
        REFERENCES chamado (id_chamado) ON DELETE CASCADE
);

CREATE TABLE escalonamento (
    id_escalonamento NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_chamado NUMBER NOT NULL,
    motivo CLOB,
    nivel NUMBER(10),
    id_setor_destino NUMBER,
    setor_destino VARCHAR2(255),
    id_grupo_destino NUMBER,
    data_escalonamento DATE,
    CONSTRAINT pk_escalonamento PRIMARY KEY (id_escalonamento),
    CONSTRAINT fk_escalonamento_chamado FOREIGN KEY (id_chamado)
        REFERENCES chamado (id_chamado) ON DELETE CASCADE,
    CONSTRAINT fk_escalonamento_setor FOREIGN KEY (id_setor_destino)
        REFERENCES setor (id_setor) ON DELETE SET NULL,
    CONSTRAINT fk_escalonamento_grupo FOREIGN KEY (id_grupo_destino)
        REFERENCES grupo_solucionadores (id_grupo_solucionadores) ON DELETE SET NULL
);

CREATE TABLE documentacao (
    id_documentacao NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    fornecedor VARCHAR2(255),
    id_grupo_solucionadores NUMBER,
    titulo VARCHAR2(255) NOT NULL,
    conteudo CLOB NOT NULL,
    data_criacao TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    id_usuario NUMBER,
    CONSTRAINT pk_documentacao PRIMARY KEY (id_documentacao),
    CONSTRAINT fk_documentacao_grupo FOREIGN KEY (id_grupo_solucionadores)
        REFERENCES grupo_solucionadores (id_grupo_solucionadores) ON DELETE SET NULL,
    CONSTRAINT fk_documentacao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

CREATE TABLE configuracao (
    id_configuracao NUMBER(10),
    workspace_name VARCHAR2(255) NOT NULL,
    support_email VARCHAR2(320) NOT NULL,
    CONSTRAINT pk_configuracao PRIMARY KEY (id_configuracao)
);

CREATE TABLE codigo_recuperacao_senha (
    id_codigo NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_grupo_solucionadores NUMBER NOT NULL,
    codigo_hash VARCHAR2(255) NOT NULL,
    criado_em TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    tentativas NUMBER(10) DEFAULT 0 NOT NULL,
    usado NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_codigo_recuperacao PRIMARY KEY (id_codigo),
    CONSTRAINT ck_codigo_recuperacao_usado CHECK (usado IN (0, 1)),
    CONSTRAINT fk_codigo_recuperacao_grupo FOREIGN KEY (id_grupo_solucionadores)
        REFERENCES grupo_solucionadores (id_grupo_solucionadores) ON DELETE CASCADE
);

CREATE INDEX idx_cliente_usuario ON cliente (id_usuario);
CREATE INDEX idx_grupo_setor ON grupo_solucionadores (id_setor);
CREATE INDEX idx_grupo_usuario ON grupo_solucionadores (id_usuario);
CREATE INDEX idx_codigo_recuperacao_usuario
    ON codigo_recuperacao_senha (id_grupo_solucionadores, criado_em);
CREATE INDEX idx_chamado_status_data ON chamado (status, data_abertura);
CREATE INDEX idx_chamado_setor ON chamado (id_setor);
CREATE INDEX idx_chamado_workspace ON chamado (id_usuario);
CREATE INDEX idx_escalonamento_chamado ON escalonamento (id_chamado);
CREATE INDEX idx_historico_chamado_data ON historico_chamado (id_chamado, data_evento);
CREATE INDEX idx_documentacao_grupo ON documentacao (id_grupo_solucionadores);
CREATE INDEX idx_documentacao_usuario ON documentacao (id_usuario);

-- Allow multiple customer users, but at most one workspace record.
CREATE UNIQUE INDEX uq_usuario_workspace_unico
    ON usuario (CASE WHEN tipo_usuario = 'WORKSPACE' THEN tipo_usuario END);

MERGE INTO configuracao target
USING (
    SELECT 1 AS id_configuracao,
           'HelpTI Suporte' AS workspace_name,
           'suporte@helpti.com.br' AS support_email
    FROM dual
) source
ON (target.id_configuracao = source.id_configuracao)
WHEN NOT MATCHED THEN
    INSERT (id_configuracao, workspace_name, support_email)
    VALUES (source.id_configuracao, source.workspace_name, source.support_email);

INSERT INTO tipo_chamado (nome, classificacao, descricao)
SELECT 'Suporte Geral', 'Suporte', 'Chamados gerais de suporte'
FROM dual
WHERE NOT EXISTS (SELECT 1 FROM tipo_chamado WHERE nome = 'Suporte Geral');

INSERT INTO tipo_chamado (nome, classificacao, descricao)
SELECT 'Hardware', 'Técnico', 'Problemas com hardware'
FROM dual
WHERE NOT EXISTS (SELECT 1 FROM tipo_chamado WHERE nome = 'Hardware');

INSERT INTO tipo_chamado (nome, classificacao, descricao)
SELECT 'Software', 'Técnico', 'Problemas com software'
FROM dual
WHERE NOT EXISTS (SELECT 1 FROM tipo_chamado WHERE nome = 'Software');

INSERT INTO tipo_chamado (nome, classificacao, descricao)
SELECT 'Rede', 'Infraestrutura', 'Problemas de rede'
FROM dual
WHERE NOT EXISTS (SELECT 1 FROM tipo_chamado WHERE nome = 'Rede');

COMMIT;
